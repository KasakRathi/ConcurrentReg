#!/usr/bin/env bash
# Start (or reuse) a throwaway MySQL 8.4 in Docker for the demo and write .demo.env with its connection settings.
# Idempotent: safe to run again. Uses port 3307 on localhost only, so a MySQL on 3306 is never touched.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/.demo.env"
NAME="creg-demo-mysql"
PORT="${CREG_DEMO_MYSQL_PORT:-3307}"

command -v docker >/dev/null || { echo "docker is not installed" >&2; exit 1; }
docker info >/dev/null 2>&1 || { echo "Docker is not running. Start Docker Desktop, then run this again." >&2; exit 1; }

# Random passwords, generated once and kept only in the git-ignored .demo.env (never committed).
if [ ! -f "$ENV_FILE" ]; then
  ROOT_PW="$(openssl rand -hex 12)"; APP_PW="$(openssl rand -hex 12)"
  cat > "$ENV_FILE" <<ENV
# Generated by scripts/demo_db.sh. Dev-only credentials for the throwaway demo database. Do not commit.
export CREG_DEMO_ROOT_PASSWORD=$ROOT_PW
export DATABASE_URL=mysql+pymysql://creg:$APP_PW@127.0.0.1:$PORT/concurrentreg_demo
export TEST_DATABASE_URL=mysql+pymysql://creg:$APP_PW@127.0.0.1:$PORT/concurrentreg_demo_test
export CREG_DEMO_CONTROLS=1
export CREG_RESULTS_DIR="$ROOT/results"
ENV
  chmod 600 "$ENV_FILE"
fi
# shellcheck disable=SC1090
source "$ENV_FILE"
APP_PW="$(echo "$DATABASE_URL" | sed -E 's#^mysql\+pymysql://creg:([^@]+)@.*#\1#')"

if ! docker ps -a --format '{{.Names}}' | grep -qx "$NAME"; then
  echo "Creating the $NAME container (first run pulls mysql:8.4)..."
  docker run -d --name "$NAME" -e MYSQL_ROOT_PASSWORD="$CREG_DEMO_ROOT_PASSWORD" -p "127.0.0.1:$PORT:3306" mysql:8.4 --max-connections=300 >/dev/null
elif ! docker ps --format '{{.Names}}' | grep -qx "$NAME"; then
  docker start "$NAME" >/dev/null
fi

echo -n "Waiting for MySQL"
for _ in $(seq 1 90); do
  if docker exec "$NAME" mysqladmin ping -uroot -p"$CREG_DEMO_ROOT_PASSWORD" --silent >/dev/null 2>&1; then break; fi
  echo -n "."; sleep 2
done
echo
docker exec "$NAME" mysqladmin ping -uroot -p"$CREG_DEMO_ROOT_PASSWORD" --silent >/dev/null 2>&1 || { echo "MySQL did not become ready" >&2; exit 1; }

docker exec -i "$NAME" mysql -uroot -p"$CREG_DEMO_ROOT_PASSWORD" 2>/dev/null <<SQL
CREATE DATABASE IF NOT EXISTS concurrentreg_demo;
CREATE DATABASE IF NOT EXISTS concurrentreg_demo_test;
CREATE USER IF NOT EXISTS 'creg'@'%' IDENTIFIED BY '$APP_PW';
GRANT ALL ON concurrentreg_demo.* TO 'creg'@'%';
GRANT ALL ON concurrentreg_demo_test.* TO 'creg'@'%';
GRANT PROCESS ON *.* TO 'creg'@'%';
FLUSH PRIVILEGES;
SQL
echo "MySQL $(docker exec "$NAME" mysqld --version | sed -E 's/.*Ver ([0-9.]+).*/\1/') is ready on 127.0.0.1:$PORT (databases: concurrentreg_demo, concurrentreg_demo_test)."
echo "Connection settings are in $ENV_FILE"
